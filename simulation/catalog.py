from dataclasses import dataclass
from enum import Enum


class ReagentCategory(Enum):
    ACID = "acid"
    BASE = "base"
    TRANSITION_METAL_SALT = "transition_metal_salt"
    INDICATOR = "indicator"
    OXIDIZER = "oxidizer"
    ORGANIC_SOLVENT = "organic_solvent"
    REDUCING_AGENT = "reducing_agent"
    HEAVY_METAL_SALT = "heavy_metal_salt"
    HALOGEN_SALT = "halogen_salt"
    NITROGEN_COMPOUND = "nitrogen_compound"
    ALKALINE_EARTH_SALT = "alkaline_earth_salt"
    MISCELLANEOUS = "miscellaneous"


class GHSPictogram(Enum):
    GHS01_EXPLODING_BOMB = "ghs01"  # Explosive / self-reactive / organic peroxide
    GHS02_FLAME = "ghs02"  # Flammable / pyrophoric / self-heating / emits flammable gas
    GHS03_FLAME_OVER_CIRCLE = "ghs03"  # Oxidizer / oxidizing gas / oxidizing liquid or solid
    GHS04_GAS_CYLINDER = "ghs04"  # Gases under pressure
    GHS05_CORROSION = "ghs05"  # Corrosive to metals / skin / eyes
    GHS06_SKULL_AND_CROSSBONES = "ghs06"  # Acute toxicity (fatal/toxic)
    GHS07_EXCLAMATION_MARK = "ghs07"  # Harmful / irritant / sensitizer / NHE
    GHS08_HEALTH_HAZARD = "ghs08"  # Carcinogen / mutagen / reprotoxic / STOT / aspiration
    GHS09_ENVIRONMENT = "ghs09"  # Hazardous to the aquatic environment


@dataclass
class Reagent:
    id: str
    name: str
    formula: str
    category: ReagentCategory
    molar_mass_g_per_mol: float
    density_g_per_ml: float
    default_color_rgba: tuple = (0.92, 0.96, 1.0, 1.0)  # water-like
    ghs_pictograms: tuple = ()
    melting_point_c: float | None = None
    boiling_point_c: float | None = None
    pka: float | None = None
    solubility_g_per_100ml_water: float | None = None
    common_uses: str = ""
    storage_note: str = ""
    hazard_statements: tuple = ()

    @property
    def molar_mass(self) -> float:
        return self.molar_mass_g_per_mol

    @property
    def density(self) -> float:
        return self.density_g_per_ml


def _ghs(*codes: GHSPictogram) -> tuple:
    return codes


def _r(*values: float) -> tuple:
    return tuple(values)


